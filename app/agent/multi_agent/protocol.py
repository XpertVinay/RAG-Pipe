"""Streaming Event Protocol and Data Transfer Objects for Collaborative Multi-Agent Workflows."""

from dataclasses import dataclass, field
import json
import time
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.models.multi_agent import AgentRole, SubTaskStatus, WorkflowStatus


class WorkflowInitRequest(BaseModel):
    """Payload to trigger a multi-agent collaborative workflow."""
    goal: str = Field(..., min_length=3, description="High-level goal or problem statement for the agent team")
    title: Optional[str] = Field(None, description="Optional brief title")
    room_id: Optional[str] = Field(None, description="Optional room or workspace scoping")
    document_ids: Optional[List[str]] = Field(None, description="Optional subset of document IDs to focus research on")
    provider: Optional[str] = Field(None, description="Preferred LLM provider (ollama, openai, gemini, etc.)")
    model: Optional[str] = Field(None, description="Preferred model name")
    anonymous: bool = Field(True, description="Enable anonymous proxying to third-party MCP providers")
    max_subtasks: int = Field(5, ge=1, le=10, description="Maximum number of atomic subtasks to decompose into")


class AgentEvent(BaseModel):
    """A structured Server-Sent Event (SSE) emitted during multi-agent execution."""
    event_type: str
    phase: str
    agent_role: str
    message: str
    progress: int = 0  # 0 to 100 percentage
    data: Dict[str, Any] = Field(default_factory=dict)
    timestamp: float = Field(default_factory=time.time)

    def to_sse(self) -> str:
        """Format as standard SSE frame."""
        payload = json.dumps(self.model_dump())
        return f"event: {self.event_type}\ndata: {payload}\n\n"


class GeneratedSubTask(BaseModel):
    """Specification of an atomic micro-task generated by Agent 2 (Task Generator)."""
    task_number: int
    title: str
    description: str
    assigned_tools: List[str] = Field(default_factory=list)
    mcp_provider: str = "native"
    dependencies: List[int] = Field(default_factory=list)
    acceptance_criteria: List[str] = Field(default_factory=list)
    input_data: Dict[str, Any] = Field(default_factory=dict)
    can_run_parallel: bool = Field(True, description="Whether this task can run in parallel in isolation")
    orchestrator_prompt: Optional[str] = Field(None, description="Direct orchestrator prompt/directive from Decision Maker")

